        p = jw_cmd_prompt();
        ok = ok && p && !strstr(p, kabe) && jw_cmd_bar_check(9005) <= 0;
        n0 = app_drawing()->ndrawn;
        clicks(&r, "B:1069;800,650;r500,500;");            /* 何も無い所・右は 何もしない */
        p = jw_cmd_prompt();
        ok = ok && p && strstr(p, kabe) && app_drawing()->ndrawn == n0;
        if (!ok)
            puts("     案内と ≪");
