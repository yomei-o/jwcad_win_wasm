        ok = ok && p && !strstr(p, kabe) && bx && !strcmp(bx, "0");
        clicks(&r, "x:1492=1.5;B:1069;");                  /* 壁があれば 解除して箱を戻す */
        bx = jw_cmd_box(1492);
