#!/usr/bin/env python3
"""Bake the ブロックツリー window's three 16x15 icons into C (src/gen/btico.h).

    python tools/mkbtico.py

CBlockTreeDialog (FUN_00416ad0) makes an image list of 16x15 pieces and loads
bitmap resources 2622, 2632 and 2642 into it, mask colour white
(decomp/res/bitmap/*.bmp, extracted with tools/rsrc.py).  The tree's items
use image 1 (a closed folder) and, selected, image 2 (an open one).
Output: 0xRRGGBB per pixel, 0xffffffff where the mask (white) is.
"""
import struct

out = ['/* generated by tools/mkbtico.py -- the block tree\'s 16x15 icons */',
       '#ifndef JW_GEN_BTICO_H', '#define JW_GEN_BTICO_H', '',
       '#define JW_BTICO_W 16', '#define JW_BTICO_H 15', '',
       'static const unsigned int jw_btico[3][15 * 16] = {']
for n in (2622, 2632, 2642):
    b = open('decomp/res/bitmap/%d.bmp' % n, 'rb').read()
    hdr, w, h, planes, bits, comp, sz, xp, yp, nc, ni = struct.unpack_from('<IiiHHIIiiII', b, 14)
    off = struct.unpack_from('<I', b, 10)[0]
    pal = []
    for i in range(16):
        bb, g, r, _ = b[14 + hdr + 4 * i:14 + hdr + 4 * i + 4]
        pal.append((r << 16) | (g << 8) | bb)
    stride = ((w * bits + 31) // 32) * 4
    rows = []
    for y in range(h):
        row = b[off + (h - 1 - y) * stride:off + (h - y) * stride]
        px = []
        for x in range(w):
            v = row[x // 2]
            v = (v >> 4) if x % 2 == 0 else (v & 15)
            c = pal[v]
            px.append('0xffffffffu' if c == 0xffffff else '0x%06xu' % c)
        rows.append(', '.join(px))
    out.append('    { /* %d */\n        %s\n    },' % (n, ',\n        '.join(rows)))
out.append('};')
out.append('')
out.append('#endif')
open('src/gen/btico.h', 'w').write('\n'.join(out) + '\n')
print('src/gen/btico.h')
