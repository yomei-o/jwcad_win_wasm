"""建具のデータ（orig/JW_OPT*.DAT）を src/gen/tgdat.inc に埋め込む。

    python tools/mktgdat.py

JW_OPT1* が建具平面 (32848)、JW_OPT2* が建具断面 (32866)、JW_OPT3* が
建具立面 (32865)、JW_OPT4* が線記号変形 (32869)。名前は原典の
ファイル選択の木に出るもの（【建具平面A】…）に合わせます。
`src/tategu.c` がこれを #include します。
"""
import glob
import os
import re

NL = chr(10)
BS = chr(92)
KIND = {'1': ('建具平面', 1), '2': ('建具断面', 2), '3': ('建具立面', 3),
        '4': ('線記号', 4)}


def cstr(b):
    """CP932 のバイト列を C の文字列に（16 進の並びが後ろの文字と繋がらないよう分ける）"""
    return '"' + '" "'.join(BS + 'x%02x' % c for c in b) + '"' if b else '""'


def main():
    files = sorted(glob.glob('orig/JW_OPT*.DAT'),
                   key=lambda p: (os.path.basename(p)[6], len(p), p))
    rows = []
    for p in files:
        m = re.match(r'JW_OPT(\d)([A-Z]?)\.DAT', os.path.basename(p), re.I)
        if not m:
            continue
        group, letter = m.group(1), (m.group(2) or 'A').upper()
        label, kind = KIND[group]
        data = open(p, 'rb').read()
        first = data.split(b'\n', 1)[0].rstrip(b'\r')
        title = first[1:] if first.startswith(b'#') else b''
        rows.append((kind, ('【%s%s】' % (label, letter)).encode('cp932'),
                     title, data))
    os.makedirs('src/gen', exist_ok=True)
    out = ['/* generated by tools/mktgdat.py from orig/JW_OPT*.DAT;'
           ' included by src/tategu.c */']
    for i, (kind, name, title, data) in enumerate(rows):
        out.append('static const unsigned char d%d[%d] = {' % (i, len(data)))
        for j in range(0, len(data), 24):
            out.append(','.join(str(b) for b in data[j:j + 24]) + ',')
        out.append('};')
    out.append('static const jw_tgdat tgdat_list[] = {')
    for i, (kind, name, title, data) in enumerate(rows):
        out.append('    { %d, %s, %s, d%d, %d },'
                   % (kind, cstr(name), cstr(title), i, len(data)))
    out.append('};')
    out.append('static const int tgdat_n = %d;' % len(rows))
    with open('src/gen/tgdat.inc', 'w', encoding='ascii', newline=NL) as f:
        f.write(NL.join(out) + NL)
    print('src/gen/tgdat.inc: %d files, %d bytes'
          % (len(rows), sum(len(r[3]) for r in rows)))


main()
