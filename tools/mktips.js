// src/gen/tips.h: the text the original shows for a command (its string table entry
// for the command id), for the tool tips of the toolbar buttons.
//   node tools/mktips.js
const fs = require('fs');
const lines = fs.readFileSync('decomp/res/string.txt', 'utf8').split(/\r?\n/);
const out = [];
for (const l of lines) {
  const m = /^\s*(\d+) 0x[0-9a-f]+\s+(.*)$/.exec(l);
  if (!m) continue;
  const id = +m[1];
  if (id < 32768 || id > 33100) continue;
  const text = m[2].trim();
  if (!text) continue;
  out.push([id, text]);
}
out.sort((a, b) => a[0] - b[0]);
const q = s => s.split(String.fromCharCode(92)).join(String.fromCharCode(92, 92)).split('"').join(String.fromCharCode(92) + '"');
const nl = String.fromCharCode(10);
let s = "/* generated by tools/mktips.js from decomp/res/string.txt: the original's status text for a command id, UTF-8 */" + nl
  + '#ifndef JW_GEN_TIPS_H' + nl + '#define JW_GEN_TIPS_H' + nl + nl
  + 'static const struct { unsigned short id; const char *text; } jw_tips[] = {' + nl;
for (const [id, t] of out) s += '    { ' + id + ', "' + q(t) + '" },' + nl;
s += '};' + nl + '#define JW_NTIPS ' + out.length + nl + nl + '#endif' + nl;
fs.writeFileSync('src/gen/tips.h', s);
console.log(out.length + ' tips');
