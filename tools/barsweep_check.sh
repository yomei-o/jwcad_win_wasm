#!/bin/sh
# `tests/barsweep_test.exe` を**命令ごとに別のプロセスで**走らせる。
#
#   sh tools/barsweep_check.sh
#
# 原典のほうは `tools/barsweep.sh` が一つの命令につき Jw_cad を一度
# 起動して、終わったら落とします。移植を一つのプロセスで十四命令
# 続けて通すと、`src/cmd.c` の静的な状態（ソリッドの入り切りなど）が
# **命令をまたいで残り**、原典と条件が揃いません。実際、矩形 の
# 矩形 (1332) は通しで走らせると「差 5」、単独で走らせると一致でした。
# 原典と同じく一命令ごとに素から始めるため、ここで分けます。
cd "$(dirname "$0")/.."
s=0; d=0; m=0
for c in 32771 32772 32773 32785 32806 32847 32870 32872 32873 \
         32874 32883 32892 32894 32908; do
    out=$(./tests/barsweep_test.exe "$c")
    echo "$out" | grep -v '^一致 '
    set -- $(echo "$out" |
             sed -n 's/^一致 \([0-9]*\)、差 \([0-9]*\)、答えなし \([0-9]*\)$/\1 \2 \3/p')
    s=$((s + $1)); d=$((d + $2)); m=$((m + $3))
done
echo "一致 $s、差 $d、答えなし $m"
