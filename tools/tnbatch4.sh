#!/bin/sh
# 天空図 (32971) の 天空率比較計算 (1066) の答え（2026-10-13）。下地は tools/tnbatch.sh と同じ。
# 天空率計算 (1323) の図を二つ描き（1323 はコマンドを選び直しても点いたまま）（中心 900,300 と 900,500、字「天空率 = …」は中心の 51 画素下）、
# 1066 で 計画建物の字 → 比較する字 → 結果を書く位置 を指示する。
#   sh tools/tnbatch4.sh [名前...]   → decomp/res/hk_tc1〜tc3（hk_c1〜c3 は日影図の答えなので別の名前）
cd "$(dirname "$0")/.."
PRE='400,300;600,300;600,300;600,500;600,500;400,500;400,500;400,300;'
H='ch:1491,10;wait:300;405,300;wait:300;595,300;wait:300;595,500;wait:300;405,500;wait:300;'
D1='pb:1064;wait:500;500,600;wait:500;pb:1323;wait:300;900,300;wait:2500;'
D2='cmd:32971;wait:1500;pb:1064;wait:500;510,600;wait:500;900,500;wait:2500;'
run() {
    [ -n "$ONLY" ] && ! echo " $ONLY " | grep -q " $1 " && return
    echo "== $1"
    sh tools/hkprobe.sh "$1" 32971 "$PRE" "$H$2"
}
ONLY="$*"
#   tc1: 計画 = 上の図の字、比較 = 下の図の字、結果は 1000,450
run tc1 "$D1${D2}cmd:32971;wait:1500;pb:1066;wait:500;900,351;wait:500;900,551;wait:500;1000,450;wait:1500;"
#   tc2: tc1 の逆（計画 = 下 83.06、比較 = 上 83.00）
run tc2 "$D1${D2}cmd:32971;wait:1500;pb:1066;wait:500;900,551;wait:500;900,351;wait:500;1000,450;wait:1500;"
#   tc3: 同じ字を二度（差 0）
run tc3 "$D1${D2}cmd:32971;wait:1500;pb:1066;wait:500;900,351;wait:500;900,351;wait:500;1000,450;wait:1500;"
