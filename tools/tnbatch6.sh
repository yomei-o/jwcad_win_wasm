#!/bin/sh
# 天空図 (32971) の 天空率比較計算 (1066) を 字だけで試す（2026-10-14）。
# 「天空率 = 83.00 %」の字を 文字 (32806) で置き、1066 で 計画 → 比較 → 結果の位置 を指示する。
#   sh tools/tnbatch6.sh [名前...]   → decomp/res/hk_cm1〜
cd "$(dirname "$0")/.."
run() {
    [ -n "$ONLY" ] && ! echo " $ONLY " | grep -q " $1 " && return
    echo "== $1"
    sh tools/hkprobeu.sh "$1" 32971 "cmd:32806;type:$2;400,300;type:$3;$4;" "pb:1066;wait:500;$5;wait:500;$6;wait:500;$7;wait:1500;"
}
ONLY="$*"
#   cm1: 二つの字が横に並ぶ（400,300 と 800,300）。計画 83.00・比較 83.06
run cm1 "天空率 = 83.00 %" "天空率 = 83.06 %" "800,300" "410,297" "810,297" "600,450"
#   cm2: 横、逆（計画 83.06・比較 83.00）
run cm2 "天空率 = 83.00 %" "天空率 = 83.06 %" "800,300" "810,297" "410,297" "600,450"
#   cm3: 差 0.01（縦に並べる）
run cm3 "天空率 = 83.00 %" "天空率 = 83.01 %" "400,400" "410,297" "410,397" "700,350"
#   cm4: 差 0.02
run cm4 "天空率 = 83.00 %" "天空率 = 83.02 %" "400,400" "410,297" "410,397" "700,350"
#   cm5: 差 0.03
run cm5 "天空率 = 83.00 %" "天空率 = 83.03 %" "400,400" "410,297" "410,397" "700,350"
#   cm6: 小数なし
run cm6 "天空率 = 83 %" "天空率 = 84 %" "400,400" "410,297" "410,397" "700,350"
#   cm7: 天空率 の字でない
run cm7 "ABC = 83.00 %" "天空率 = 84.00 %" "400,400" "410,297" "410,397" "700,350"
