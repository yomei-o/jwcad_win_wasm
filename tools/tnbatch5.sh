#!/bin/sh
# 天空図 (32971) の 三斜 (1068) の釦（2026-10-14）。下地は tools/tnbatch4.sh と同じ（建物 + 高さ 10）。
#   sh tools/tnbatch5.sh [名前...]   → decomp/res/hk_sa1〜
cd "$(dirname "$0")/.."
PRE='400,300;600,300;600,300;600,500;600,500;400,500;400,500;400,300;'
H='ch:1491,10;wait:300;405,300;wait:300;595,300;wait:300;595,500;wait:300;405,500;wait:300;'
run() {
    [ -n "$ONLY" ] && ! echo " $ONLY " | grep -q " $1 " && return
    echo "== $1"
    sh tools/hkprobe.sh "$1" 32971 "$PRE" "$H$2"
}
ONLY="$*"
#   sa1: 三斜、釦はそのまま（1329 切）
run sa1 "pb:1068;wait:500;500,600;wait:500;900,300;wait:3000;"
#   sa2: 三斜計算 (1329) を入れる
run sa2 "pb:1068;wait:500;520,610;wait:500;pb:1329;wait:500;900,300;wait:3000;"
#   sa3: 建物位置確認表 (2114) だけ
run sa3 "pb:1068;wait:500;520,610;wait:500;pb:2114;wait:500;900,300;wait:3000;"
#   sa4: 三斜計算 と 建物位置確認表 の両方
run sa4 "pb:1068;wait:500;520,610;wait:500;pb:1329;wait:500;pb:2114;wait:500;900,300;wait:3000;"
#   sa5: 三斜計算 で 基準建物用 (1689)
run sa5 "pb:1068;wait:500;520,610;wait:500;pb:1689;wait:300;pb:1329;wait:500;900,300;wait:3000;"
#   sa6: 三斜計算 で 最大分割角度 (2210) を 5 に
run sa6 "pb:1068;wait:500;520,610;wait:500;pb:1329;wait:500;cbsel:2210,0;wait:300;900,300;wait:3000;"
run sa7 "pb:1068;wait:500;520,610;wait:500;pb:1329;wait:500;cbsel:2210,2;wait:300;900,300;wait:3000;"
#   sa8: 建物が二つ（高さ 10 と 6）で 建物位置確認表 + 三斜計算
PRE2='400,300;600,300;600,300;600,500;600,500;400,500;400,500;400,300;650,380;750,380;750,380;750,450;750,450;650,450;650,450;650,380;'
H2='ch:1491,10;wait:300;405,300;wait:300;595,300;wait:300;595,500;wait:300;405,500;wait:300;ch:1491,6;wait:300;655,380;wait:300;745,380;wait:300;745,450;wait:300;655,450;wait:300;'
[ -n "$ONLY" ] && ! echo " $ONLY " | grep -q " sa8 " || { echo "== sa8"; sh tools/hkprobe.sh sa8 32971 "$PRE2" "${H2}pb:1068;wait:500;520,610;wait:500;pb:2114;wait:500;pb:1329;wait:500;900,300;wait:3000;"; }
