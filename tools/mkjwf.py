#!/usr/bin/env python3
"""Bake the original's own 環境設定ファイル into C (src/gen/jwf.h).

    python tools/mkjwf.py

decomp/res/env_new.jwf is what 設定 > 環境設定ファイル > 書出し wrote with
decomp/res/new.jww open (tools/jwdraw.ps1: `raw:f,273,32924,0;savedlg:...`).
It is a text file of 303 lines, CRLF, CP932: S_COMM_n, LAYSCALE, LCOLLOR_k,
PCOLLOR_k, MWIDE, MHIGH, MDIST, MPEN, LAYNAM_h, LAYCOL_h, LAYWID_h, LAYTYP_h,
the keys of the letters, and so on.  The port writes one by taking this and
putting in the values it holds (src/cmd.c, jw_env_write); everything else
goes out as the original's fresh start has it.
"""
b = open('decomp/res/env_new.jwf', 'rb').read()
out = ['/* generated by tools/mkjwf.py from decomp/res/env_new.jwf */',
       '#ifndef JW_GEN_JWF_H', '#define JW_GEN_JWF_H', '',
       '#define JW_JWF_LEN %d' % len(b), '',
       'static const unsigned char jw_jwf_tpl[JW_JWF_LEN] = {']
for i in range(0, len(b), 16):
    out.append('    ' + ', '.join('0x%02x' % c for c in b[i:i + 16]) + ',')
out.append('};')
out.append('')
out.append('#endif')
open('src/gen/jwf.h', 'w').write('\n'.join(out) + '\n')
print('src/gen/jwf.h', len(b))
