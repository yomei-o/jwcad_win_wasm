#!/usr/bin/env python3
"""src/gen/tips.h: the text the original shows for a command (its string table
entry for the command id), for the tool tips of the toolbar buttons.

    python tools/mktips.py          (reads decomp/res/string.txt, which is committed)

The same thing tools/mktips.js does -- this one is here so that tools/gen.sh
needs nothing but python (node is not on a new machine's PATH).
"""
import io
import re

out = []
with io.open('decomp/res/string.txt', encoding='utf-8') as f:
    for l in f.read().splitlines():
        m = re.match(r'^\s*(\d+) 0x[0-9a-f]+\s+(.*)$', l)
        if not m:
            continue
        i = int(m.group(1))
        if i < 32768 or i > 33100:
            continue
        text = m.group(2).strip()
        if not text:
            continue
        out.append((i, text))
out.sort(key=lambda e: e[0])


def q(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


s = ("/* generated by tools/mktips.js from decomp/res/string.txt: the original's status text for a "
     "command id, UTF-8 */\n"
     "#ifndef JW_GEN_TIPS_H\n#define JW_GEN_TIPS_H\n\n"
     "static const struct { unsigned short id; const char *text; } jw_tips[] = {\n")
for i, t in out:
    s += '    { %d, "%s" },\n' % (i, q(t))
s += '};\n#define JW_NTIPS %d\n\n#endif\n' % len(out)
with io.open('src/gen/tips.h', 'w', encoding='utf-8', newline='\n') as f:
    f.write(s)
print('%d tips' % len(out))
