// cmdlist.js: the original's commands by name, for the page's command search (Ctrl+K).
// Names and menu paths come from decomp/res/menu.txt, the explanations from the string table
// (decomp/res/string.txt).  Only the ids the port answers are kept: docs/command-coverage.md says which
// (status 動く or フロントエンド).        node tools/mkcmdlist.js
const fs = require('fs');
const nl = String.fromCharCode(10);
const menu = fs.readFileSync('decomp/res/menu.txt', 'utf8').split(/\r?\n/);
const strs = new Map();
for (const l of fs.readFileSync('decomp/res/string.txt', 'utf8').split(/\r?\n/)) {
  const m = /^\s*(\d+) 0x[0-9a-f]+\s+(.*)$/.exec(l);
  if (m) strs.set(+m[1], m[2].trim());
}
const cov = new Map();
for (const l of fs.readFileSync('docs/command-coverage.md', 'utf8').split(/\r?\n/)) {
  const m = /^\|\s*(\d+)\s*\|[^|]*\|\s*([^|]+?)\s*\|/.exec(l);
  if (m) cov.set(+m[1], m[2]);
}
const out = [];
const seen = new Set();
const stack = [];                       // the popup names above the item being read
for (const l of menu) {
  let m = /^(\s*)POPUP "([^"]*)"/.exec(l);
  if (m) {
    const depth = m[1].length / 2;
    stack.length = depth;
    stack[depth] = m[2].replace(/\(&.\)|&/g, '').replace(/[\[\]]/g, '').trim();
    continue;
  }
  m = /^(\s*)MENUITEM "([^"]*)", (\d+)/.exec(l);
  if (!m) continue;
  const id = +m[3];
  if (seen.has(id)) continue;
  const st = cov.get(id);
  if (st !== '動く' && st !== 'フロントエンド') continue;
  const name = m[2].split('\t')[0].replace(/\(&.\)/g, '').replace(/&/g, '').replace(/\.\.\.$/, '').trim();
  if (!name || id >= 57600 && id < 57700 && !strs.has(id) && false) continue;
  seen.add(id);
  const depth = m[1].length / 2;
  out.push([id, name, strs.get(id) || '', stack.slice(0, depth).filter(Boolean).join(' > ')]);
}
const js = '// generated by tools/mkcmdlist.js from decomp/res/menu.txt, string.txt and docs/command-coverage.md' + nl
  + 'window.JW_CMDS = ' + JSON.stringify(out).split('],[').join('],' + nl + '[') + ';' + nl;
fs.writeFileSync('cmdlist.js', js);
console.log(out.length + ' commands -> cmdlist.js (' + js.length + ' bytes)');
